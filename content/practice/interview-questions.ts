/**
 * Interview Prep question catalog (IBM i Practice Hub -- phase 1 of a
 * two-phase rollout).
 *
 * Phase 1 (this file, as of this PR): all 764 questions from the project's
 * master interview-question bank (docs/tutorials/IBMi Interview Questions/
 * IBM_i_Interview_Questions_Master_onlyQuestions.md) are imported with
 * stable ids, their original source numbering, a topic/difficulty/
 * questionType classification, and legacy/release-dependent/duplicate
 * flags where relevant -- but every single record has `status: 'draft'`.
 * No answer content (`modelAnswer`/`essentialPoints`/`commonMistakes`) was
 * written for any record in this PR -- a separate answers document exists
 * but was deliberately NOT used, and no placeholder/fabricated answer was
 * generated for any question. `InterviewQuestion` is a discriminated union
 * on `status` specifically so this is enforced by the type system, not
 * just convention: a `'draft'` record is structurally incapable of
 * carrying `modelAnswer`/`essentialPoints`/`commonMistakes` at all.
 *
 * isInterviewPrepAvailable() -- unchanged from before this PR -- only
 * counts `'published'` entries, so it correctly returns `false` today
 * (confirmed by this file's own regression coverage). The landing page
 * now DOES call it and DOES render a real /practice/interview route (see
 * app/(authenticated)/practice/page.tsx and .../practice/interview/
 * page.tsx) -- unlike the pre-this-PR state, where the card was an
 * unconditional ComingSoonCard that never read this file at all. The new
 * page strictly shows only `status === 'published'` questions (currently
 * zero), with a professional "in review" empty state -- it never renders
 * an unreviewed prompt to a real visitor, matching this codebase's
 * established draft-content convention (getPublishedLessons(),
 * isDeepDiveAvailable(), isInsightAvailable() all work the same way).
 *
 * Phase 2 (a separate, future PR, out of scope here): author reviewed
 * model answers/essential points/common mistakes for a first batch of
 * questions and flip those specific records to `status: 'published'` --
 * at which point the already-built topic nav/search/filter UI on
 * /practice/interview activates for them automatically, with zero further
 * UI changes required.
 *
 * Classification methodology (first-pass, meant for human review, not
 * claimed as verified-accurate for all 764 records):
 *  - `topicId` reuses one of the 19 subject-matter ids
 *    lib/practice-topic-groups.ts's consolidated picker already uses (the
 *    22 PRACTICE_TOPICS ids minus `interview-readiness`, `mini-projects`,
 *    `mixed-review`). `interview-readiness` is deliberately never used
 *    here -- it's an existing, populated Guided-Practice topic (general
 *    career/behavioral readiness content), a different meaning than this
 *    bank's purely technical questions; reusing it would create a
 *    confusing content collision under one id.
 *  - `difficulty`/`questionType`/topic classification, and the
 *    `legacyContext`/`releaseDependent`/`duplicateOf` flags, were derived
 *    by a documented, keyword-pattern-based classifier (not ad hoc
 *    per-question guessing) so the methodology itself is auditable and
 *    reproducible -- see the PR description for the exact rule categories
 *    used. `duplicateOf` links a near-duplicate to an earlier-numbered
 *    canonical entry; both records are always kept, never silently
 *    dropped.
 *  - A small number of records had their wording lightly cleaned up
 *    (typos, awkward phrasing) without changing technical meaning;
 *    `originalNumber` always traces back to the exact source-document
 *    question for verification against the committed source file.
 */

import type { PracticeDifficulty } from './questions'

export type InterviewQuestionType = 'conceptual' | 'scenario-based' | 'code-based'

interface InterviewQuestionBase {
  /** Stable, e.g. 'iq-001' -- never renumbered even if topic/order changes. */
  id: string
  /** 1-764, traceability back to the source master doc's own numbering. */
  originalNumber: number
  /** One of the 19 subject-matter PRACTICE_TOPICS ids -- see file header. */
  topicId: string
  difficulty: PracticeDifficulty
  questionType: InterviewQuestionType
  prompt: string
  /** [] for every record in this PR -- cross-referencing 764 questions to ~288 lessons is deferred to a future pass. */
  relatedLessonSlugs: string[]
  tags: string[]
  /** RPG/400 fixed-form-only, DDS-era SDA/RLU/PDM/SEU tooling, Query/400, or other concepts with no direct modern-ILE equivalent -- surfaced, not silently reclassified. */
  legacyContext?: boolean
  /** The eventual answer depends on IBM i release/PTF specifics that must be verified before publishing. */
  releaseDependent?: boolean
  /** Set when this question is a near-duplicate of another id -- both entries are kept, linked for a future consolidation pass, never silently dropped. */
  duplicateOf?: string
}

/**
 * Discriminated on `status` -- a `'draft'` entry is structurally incapable
 * of carrying `modelAnswer`/`essentialPoints`/`commonMistakes` (they don't
 * exist on that branch of the union at all), while a `'published'` entry
 * requires them. This makes "unanswered questions stay unpublished" a
 * compile-time guarantee, not just a convention every record has to
 * remember to follow.
 */
export type InterviewQuestion =
  | (InterviewQuestionBase & { status: 'draft' })
  | (InterviewQuestionBase & {
      status: 'published'
      modelAnswer: string
      essentialPoints: string[]
      commonMistakes: string[]
      followUpQuestions?: string[]
    })

